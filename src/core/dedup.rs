use anyhow::{Context, Result, bail};
use image::imageops::FilterType;
use image::{DynamicImage, ImageFormat};
use std::io::Cursor;

/// Maximum accepted raw text size (4 MiB). Larger copies are safely ignored to protect UI/DB latency.
pub const MAX_TEXT_BYTES: usize = 4 * 1024 * 1024;

/// Maximum accepted raw image payload size (32 MiB).
pub const MAX_IMAGE_BYTES: usize = 32 * 1024 * 1024;

/// Maximum characters stored in the lightweight `preview_text` column.
pub const MAX_PREVIEW_CHARS: usize = 220;

/// Thumbnail bounding box dimensions (in pixels) stored on disk for fast list rendering.
pub const THUMB_MAX_WIDTH: u32 = 160;
pub const THUMB_MAX_HEIGHT: u32 = 96;

/// Known MIME markers emitted by password managers or OS security mechanisms
/// indicating that clipboard content must NOT be persisted in history.
const SENSITIVE_MIME_MARKERS: &[&str] = &[
    "x-kde-passwordmanagerhint",
    "application/x-password",
    "org.nspasteboard.concealedtype",
    "org.nspasteboard.transienttype",
    "org.nspasteboard.autogeneratedtype",
    "application/x-nspasteboard-concealed",
    "excludeclipboardcontentfrommonitorprocessing",
    "canincludeinclipboardhistory",
];

/// Returns `true` if the offered MIME types mark the clipboard payload as sensitive/transient.
pub fn is_sensitive_mime_list(mime_types: &[String]) -> bool {
    mime_types.iter().any(|mime| {
        let lower = mime.to_ascii_lowercase();
        SENSITIVE_MIME_MARKERS
            .iter()
            .any(|marker| lower == *marker || lower.contains("passwordmanagerhint"))
    })
}

/// Computes the canonical BLAKE3 hex hash for text, ignoring leading and trailing whitespace.
/// Returns `None` if the trimmed text is empty.
pub fn hash_trimmed_text(text: &str) -> Option<String> {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return None;
    }
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"clipflow:text:v1\0");
    hasher.update(trimmed.as_bytes());
    Some(hasher.finalize().to_hex().to_string())
}

/// Builds a compact single-line preview string suitable for fixed-height virtualized list rows.
pub fn build_text_preview(text: &str) -> String {
    let trimmed = text.trim();
    let mut out = String::with_capacity(trimmed.len().min(MAX_PREVIEW_CHARS));
    let mut prev_ws = false;
    let mut count = 0usize;
    let mut truncated = false;

    for ch in trimmed.chars() {
        if count >= MAX_PREVIEW_CHARS {
            truncated = true;
            break;
        }
        if ch == '\n' || ch == '\r' {
            if !out.ends_with(" ↵ ") && !out.is_empty() {
                out.push_str(" ↵ ");
                count += 3;
            }
            prev_ws = true;
        } else if ch.is_whitespace() {
            if !prev_ws {
                out.push(' ');
                count += 1;
                prev_ws = true;
            }
        } else {
            out.push(ch);
            count += 1;
            prev_ws = false;
        }
    }

    if truncated {
        out.push('…');
    }
    out
}

/// Normalized image ready for content-addressed disk storage and deduplication.
#[derive(Debug, Clone)]
pub struct NormalizedImage {
    pub content_hash: String,
    pub png_bytes: Vec<u8>,
    pub thumb_png_bytes: Vec<u8>,
    pub width: u32,
    pub height: u32,
    pub search_text: String,
    pub preview_text: String,
}

/// Decodes an incoming image payload, computes a pixel-canonical BLAKE3 hash (so re-encoded
/// identical screenshots still deduplicate), produces canonical PNG bytes, and generates a small thumbnail.
pub fn normalize_image(raw_bytes: &[u8]) -> Result<NormalizedImage> {
    if raw_bytes.is_empty() {
        bail!("empty image payload");
    }
    if raw_bytes.len() > MAX_IMAGE_BYTES {
        bail!(
            "image exceeds max allowed size ({} > {} bytes)",
            raw_bytes.len(),
            MAX_IMAGE_BYTES
        );
    }

    let decoded = image::load_from_memory(raw_bytes).context("failed to decode clipboard image")?;
    let rgba = decoded.to_rgba8();
    let (width, height) = rgba.dimensions();
    if width == 0 || height == 0 {
        bail!("zero-dimension image");
    }

    let mut hasher = blake3::Hasher::new();
    hasher.update(b"clipflow:image:v1\0");
    hasher.update(&width.to_le_bytes());
    hasher.update(&height.to_le_bytes());
    hasher.update(rgba.as_raw());
    let content_hash = hasher.finalize().to_hex().to_string();

    // Preserve original PNG bytes if already PNG; otherwise encode to PNG for uniform clipboard output.
    let png_bytes = if matches!(image::guess_format(raw_bytes), Ok(ImageFormat::Png)) {
        raw_bytes.to_vec()
    } else {
        encode_png(&DynamicImage::ImageRgba8(rgba.clone()))?
    };

    let thumb_img = DynamicImage::ImageRgba8(rgba).thumbnail(THUMB_MAX_WIDTH, THUMB_MAX_HEIGHT);
    let thumb_png_bytes = encode_png(&thumb_img)?;

    let preview_text = format!("Image {}×{}", width, height);
    let search_text = format!("image png {}x{} {}×{}", width, height, width, height);

    Ok(NormalizedImage {
        content_hash,
        png_bytes,
        thumb_png_bytes,
        width,
        height,
        search_text,
        preview_text,
    })
}

fn encode_png(img: &DynamicImage) -> Result<Vec<u8>> {
    let mut cursor = Cursor::new(Vec::new());
    img.write_to(&mut cursor, ImageFormat::Png)
        .context("failed to encode PNG")?;
    Ok(cursor.into_inner())
}

/// Helper used by tests or callers that already have a `DynamicImage` and want a crisp resized preview.
#[allow(dead_code)]
pub fn resize_for_preview(img: &DynamicImage, max_w: u32, max_h: u32) -> DynamicImage {
    img.resize(max_w, max_h, FilterType::Triangle)
}
